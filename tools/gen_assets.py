C = {'.':0,'-':1,'+':2,'#':3}
def tile(rows):
    assert len(rows)==8, rows
    out=[]
    for r in rows:
        assert len(r)==8, r
        lo=hi=0
        for i,ch in enumerate(r):
            v=C[ch]; b=7-i
            lo|=(v&1)<<b; hi|=((v>>1)&1)<<b
        out+= [lo,hi]
    return out
def split16(rows):
    assert len(rows)==16
    for r in rows: assert len(r)==16, r
    TL=[r[:8] for r in rows[:8]]; TR=[r[8:] for r in rows[:8]]
    BL=[r[:8] for r in rows[8:]]; BR=[r[8:] for r in rows[8:]]
    return [tile(TL),tile(TR),tile(BL),tile(BR)]

