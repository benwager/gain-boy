// ============================================================
//  GAIN BOY - sound engine (ROM bank 1)
//
//  Game Boy hardware: 4 channels
//    CH1 pulse  — kick body, snare tone, whooshes (sweep-capable)
//    CH2 pulse  — lead melody, echo taps, chord stabs
//    CH3 wave   — bass, synth double, melody loops (wavetables[])
//    CH4 noise  — hats, snare body, crash, clicks
//
//  Envelope bytes are hardware format: high nibble = volume (0–F),
//  low 3 bits = fade speed (0 = sustain). Duty is 0..3 (12.5%..75%).
// ============================================================
#pragma bank 1
#include "game.h"
#include "band.h"

/* MIDI note → hardware period (table generated by tools/gen_assets.py). */
uint16_t nfreq(int16_t m) {
    while (m < 36) m += 12;
    while (m > 96) m -= 12;
    return note_tbl[m - 36];
}

/* Raw CH1 write: period x, NR10 sweep, duty 0–3, envelope. */
void ch1_raw(uint16_t x, uint8_t sweep, uint8_t duty, uint8_t env) {
    NR10_REG = sweep; NR11_REG = duty << 6; NR12_REG = env;
    NR13_REG = x & 0xFF; NR14_REG = 0x80 | (x >> 8);
}

/* Raw CH4 noise: length, envelope, polynomial (clock + width). */
void noise_hit(uint8_t len, uint8_t env, uint8_t poly) {
    NR41_REG = len; NR42_REG = env; NR43_REG = poly; NR44_REG = 0xC0;
}

/* ---- drum voices -------------------------------------------------------
 * Kick: CH1 starts high (`KICK_X`) and sweeps down — a pitch envelope kick.
 * Snare: short CH1 + noise; some songs add a delayed noise “clap” flam.
 * Hats / crash: noise only, different length / envelope / poly.
 */
void kick(void)  { ch1_raw(KICK_X, 0x19, 2, 0xF1); }   /* sweep 0x19 = fast down */
void snare(void) {
    ch1_raw(1400, 0x1A, 2, 0x81);                       /* tonal body */
    noise_hit(42, 0xA1, 0x22);                          /* noise crack */
    if (songs[song].clap) clap_frames = 3;              /* 2nd hit 2 frames later */
}
void hat(void)   { noise_hit(59, 0x40, 0x00); }          /* closed, short */
void ohat(void)  { noise_hit(36, 0x52, 0x00); }          /* open, longer */
void crash(void) { noise_hit(10, 0x93, 0x01); }          /* bright / long */
void click(void) { noise_hit(62, 0x91, 0x00); }          /* kick beater click */

/* Pan CH2 only: 0 = centre, 1 = left, 2 = right (echo ping-pong). */
void pan2(uint8_t where) {
    uint8_t r = NR51_REG & ~0x22;
    NR51_REG = r | (where == 0 ? 0x22 : where == 1 ? 0x20 : 0x02);
}

/* Melody on CH2. `m` = MIDI note. FX: LONG NOTES doubles fade time. */
void lead(uint8_t m, uint8_t env, uint8_t where) {
    uint16_t f = nfreq(m);
    pan2(where);
    if (sustain) env &= 0xF0;                           /* held ↓: no decay */
    if (fx_id == 1) {                                   /* LONG NOTES power-up */
        uint8_t p = env & 7;
        env = (env & 0xF8) | (p ? (p * 2 > 7 ? 7 : p * 2) : 0);
    }
    NR21_REG = songs[song].lead_duty << 6; NR22_REG = env;
    NR23_REG = f & 0xFF; NR24_REG = 0x80 | (f >> 8);
    live_x = f; live_frames = 0; live_x_valid = 1;      /* vibrato tracks this */
}

/* CH3 tone. Wavetable must already be loaded (`use_wave`). */
void wave_note(uint8_t m, uint8_t len, uint8_t vol) {
    uint16_t f = nfreq(m + 12);
    NR30_REG = 0x80; NR31_REG = len; NR32_REG = vol;
    NR33_REG = f & 0xFF; NR34_REG = 0xC0 | (f >> 8);
}

void load_wave(uint8_t w) {
    NR30_REG = 0x00;
    volatile uint8_t *r = (volatile uint8_t *)0xFF30;
    for (uint8_t i = 0; i < 16; i++) r[i] = wavetables[w][i];
}
uint8_t cur_wave = 255;
void use_wave(uint8_t w) { if (w != cur_wave) { load_wave(w); cur_wave = w; } }

/* ---- harmony -----------------------------------------------------------
 * Floor keys map through key_off_* + song root (+ optional key-shift).
 * Pads override the automatic progression for a few bars.
 */
int8_t chord_semi(void) {
    const Song *v = &songs[song];
    if (override_bars) return v->minor ? pad_semi_min[pad_chord] : pad_semi_maj[pad_chord];
    return cur_prog[bar & 3];
}
uint8_t chord_is_minor(void) {
    const Song *v = &songs[song];
    if (override_bars) return ((v->minor ? pad_min_min : pad_min_maj) >> pad_chord) & 1;
    return (cur_pmask >> (bar & 3)) & 1;
}
uint8_t key_note(uint8_t k) {
    if (k > 9) k = 9;
    return ROOT + (songs[song].minor ? key_off_min[k] : key_off_maj[k]);
}

/* Star-key mask: keys whose pitch class is in the current triad. */
void calc_glow(void) {
    const Song *v = &songs[song];
    const uint8_t *p = v->minor ? pent_min : pent_maj;
    int8_t ch = chord_semi();
    uint8_t c0 = (uint8_t)((ch + 24) % 12);
    uint8_t c1 = (uint8_t)((ch + 24 + (chord_is_minor() ? 3 : 4)) % 12);
    uint8_t c2 = (uint8_t)((ch + 31) % 12);
    glow_mask = 0;
    for (uint8_t k = 0; k < 8; k++) {
        uint8_t pc = p[k < 5 ? k : k - 5];
        if (pc == c0 || pc == c1 || pc == c2) glow_mask |= (1 << k);
    }
}
void draw_glow(uint8_t mask) {
    if (mask == glow_shown) return;
    uint8_t changed = mask ^ glow_shown;
    glow_shown = mask;
    for (uint8_t k = 0; k < 8; k++)
        if (((changed >> k) & 1) && k != lit_key) draw_key(k, 0);
}

/* Fast-arp chord on CH2 (pads / star power). Queues 3 frequencies in stab_x[]. */
void strum(uint8_t pad, uint8_t env) {
    const Song *v = &songs[song];
    int8_t semi = v->minor ? pad_semi_min[pad] : pad_semi_maj[pad];
    uint8_t minor = ((v->minor ? pad_min_min : pad_min_maj) >> pad) & 1;
    uint8_t base = ROOT + semi; if (base > ROOT + 6) base -= 12;
    stab_x[0] = nfreq(base + 12);
    stab_x[1] = nfreq(base + 12 + (minor ? 3 : 4));
    stab_x[2] = nfreq(base + 19);
    pan2(0); NR21_REG = 0x80; NR22_REG = env;
    NR23_REG = stab_x[0] & 0xFF; NR24_REG = 0x80 | (stab_x[0] >> 8);
    stab_frames = 18; live_x_valid = 0;
}

/* Queue two delayed CH2 hits (echo1 then echo2). BREAKDOWN / ECHO FX force a
 * bigger dotted-8th ping-pong regardless of the song’s echo_t. */
void echo_push(uint8_t m) {
    const Song *v = &songs[song];
    uint8_t d[2]; d[0] = v->echo_t; d[1] = v->echo_t * 2;
    uint8_t env[2]; env[0] = v->echo1; env[1] = v->echo2;
    if (fx_id == 2 || stut) { d[0] = 3; d[1] = 6; env[0] = 0x93; env[1] = 0x73; }
    for (uint8_t r = 0; r < 2; r++)
        for (uint8_t i = 0; i < NECHO; i++) if (!e_on[i]) {
            e_on[i] = 1; e_due[i] = tick + d[r]; e_note[i] = m; e_env[i] = env[r]; break;
        }
}
